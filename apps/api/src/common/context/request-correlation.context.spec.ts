import { createServer } from 'node:http';
import { Request, Response } from 'express';
import request from 'supertest';
import { RequestCorrelationContext } from './request-correlation.context.js';
import { RequestCorrelationMiddleware } from '../middlewares/request-correlation.middleware.js';

function createCorrelationServer() {
  const context = new RequestCorrelationContext();
  const middleware = new RequestCorrelationMiddleware(context);
  return createServer((incomingRequest, outgoingResponse) => {
    middleware.use(
      incomingRequest as Request,
      outgoingResponse as unknown as Response,
      () => {
        setImmediate(() => {
          outgoingResponse.setHeader('content-type', 'application/json');
          outgoingResponse.end(
            JSON.stringify({ requestId: context.getRequestId() }),
          );
        });
      },
    );
  });
}

describe('Request correlation', () => {
  it('echoes a valid bounded request ID and preserves it across async work', async () => {
    const response = await request(createCorrelationServer())
      .get('/correlation')
      .set('x-request-id', 'request.Valid-123_')
      .expect(200);

    expect(response.headers['x-request-id']).toBe('request.Valid-123_');
    expect(response.body).toEqual({ requestId: 'request.Valid-123_' });
  });

  it('replaces an invalid request ID with one generated by the API', async () => {
    const response = await request(createCorrelationServer())
      .get('/correlation')
      .set('x-request-id', 'invalid request id')
      .expect(200);

    expect(response.headers['x-request-id']).toMatch(
      /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/,
    );
    expect(response.body).toEqual({
      requestId: response.headers['x-request-id'],
    });
  });
});
